#!/usr/bin/env node
/**
 * Lists every document referenced in src/data/products.ts that is not
 * present under public/, and writes docs/missing-documents.md.
 *
 * Usage: node scripts/missing-documents.mjs
 *
 * The product data file is TypeScript; rather than compiling it we extract
 * the document paths with a regex over the generated helper output of
 * `panelDocs()` / `boothDocs()` — i.e. we replicate the naming convention
 * (/documents/<slug>/<id>.<ext>) for the known ids per family.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(new URL(import.meta.url).pathname), '..');
const src = readFileSync(resolve(root, 'src/data/products.ts'), 'utf8');

// slug → family, in declaration order
const products = [];
const re = /slug: '([a-z0-9-]+)',\s*\n\s*family: '(textile|rwood|rpet|booth)'/g;
let m;
while ((m = re.exec(src))) products.push({ slug: m[1], family: m[2] });

const PANEL = ['datasheet.pdf', 'installation-guide.pdf', 'acoustic-test-report.pdf', 'colour-finish-guide.pdf', 'fire-certificate.pdf', 'sustainability-declaration.pdf'];
const BOOTH = ['datasheet.pdf', 'installation-manual.pdf', 'acoustic-test-report.pdf', 'cad-drawing.dwg', 'warranty.pdf', 'sustainability-declaration.pdf'];

const rows = [];
let missing = 0, present = 0;
for (const p of products) {
  const files = p.family === 'booth' ? BOOTH : PANEL;
  for (const f of files) {
    const rel = `/documents/${p.slug}/${f}`;
    const ok = existsSync(resolve(root, 'public', rel.slice(1)));
    if (ok) present++; else missing++;
    rows.push({ slug: p.slug, file: rel, ok });
  }
}

const lines = [];
lines.push('# Missing product documents');
lines.push('');
lines.push(`Generated by \`node scripts/missing-documents.mjs\` on ${new Date().toISOString().slice(0, 10)}.`);
lines.push('');
lines.push(`Every product page links its documents from \`src/data/products.ts\` as \`/documents/<slug>/<document>.<ext>\`. ${present} of ${present + missing} referenced files are in the repository; the ${missing} below are linked but **not present** and return 404 until the PDF is added under \`public/documents/<slug>/\`.`);
lines.push('');
lines.push('| Product | Missing file |');
lines.push('|---|---|');
for (const r of rows.filter((r) => !r.ok)) lines.push(`| ${r.slug} | \`${r.file}\` |`);
lines.push('');
lines.push('## Present');
lines.push('');
for (const r of rows.filter((r) => r.ok)) lines.push(`- \`${r.file}\``);
lines.push('');

mkdirSync(resolve(root, 'docs'), { recursive: true });
writeFileSync(resolve(root, 'docs/missing-documents.md'), lines.join('\n'));
console.log(`${present} present, ${missing} missing → docs/missing-documents.md`);
