#!/usr/bin/env node
/**
 * Lists every document referenced in src/data/products.ts that has no file
 * under public/documents, and writes docs/missing-documents.md.
 *
 * Usage: node scripts/missing-documents.mjs
 *
 * The product data file is TypeScript; rather than compiling it we replicate
 * the document sets per family (panelDocs / boothDocs) and the file rules of
 * src/lib/documents.ts: a document exists when its folder holds an upload
 * named re-sound-<anything>-<id>-<locale>.pdf|dwg or the legacy <id>.<ext>.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(new URL(import.meta.url).pathname), '..');
const src = readFileSync(resolve(root, 'src/data/products.ts'), 'utf8');

// slug → family, in declaration order
const products = [];
const re = /slug: '([a-z0-9-]+)',\s*\n\s*family: '(textile|rwood|rpet|booth)'/g;
let m;
while ((m = re.exec(src))) products.push({ slug: m[1], family: m[2] });

const PANEL = ['datasheet', 'installation-guide', 'acoustic-test-report', 'colour-finish-guide', 'fire-certificate', 'sustainability-declaration'];
const BOOTH = ['datasheet', 'installation-manual', 'acoustic-test-report', 'cad-drawing', 'warranty', 'sustainability-declaration'];

const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
/** The file behind (slug, id), by the rules of src/lib/documents.ts, or null. */
function fileFor(slug, id) {
  const dir = resolve(root, 'public', 'documents', slug);
  const names = existsSync(dir) ? readdirSync(dir) : [];
  const upload = names.find((n) => new RegExp(`^re-sound-.+-${escapeRe(id)}-[a-z]{2}\\.(pdf|dwg)$`, 'i').test(n));
  if (upload) return `/documents/${slug}/${upload}`;
  const legacy = names.find((n) => n === `${id}.pdf` || n === `${id}.dwg`);
  return legacy ? `/documents/${slug}/${legacy}` : null;
}

const rows = [];
let missing = 0, present = 0;
for (const p of products) {
  const ids = p.family === 'booth' ? BOOTH : PANEL;
  for (const id of ids) {
    const file = fileFor(p.slug, id);
    if (file) present++; else missing++;
    rows.push({ slug: p.slug, id, file: file ?? `/documents/${p.slug}/re-sound-${p.slug}-${id}-en.pdf`, ok: Boolean(file) });
  }
}

const lines = [];
lines.push('# Missing product documents');
lines.push('');
lines.push(`Generated by \`node scripts/missing-documents.mjs\` on ${new Date().toISOString().slice(0, 10)}.`);
lines.push('');
lines.push(`Every product page offers the documents listed for it in \`src/data/products.ts\` (behind the lead form, e-mailed by /api/document) as long as a file exists under \`public/documents/<slug>/\` — see \`public/documents/README.md\` for the file names. ${present} of ${present + missing} documents have a file; the ${missing} below have **none** and show no card until the PDF is added (the expected upload name is given).`);
lines.push('');
lines.push('| Product | Missing file |');
lines.push('|---|---|');
for (const r of rows.filter((r) => !r.ok)) lines.push(`| ${r.slug} | \`${r.file}\` |`);
lines.push('');
lines.push('## Present');
lines.push('');
for (const r of rows.filter((r) => r.ok)) lines.push(`- \`${r.file}\``);
lines.push('');

mkdirSync(resolve(root, 'docs'), { recursive: true });
writeFileSync(resolve(root, 'docs/missing-documents.md'), lines.join('\n'));
console.log(`${present} present, ${missing} missing → docs/missing-documents.md`);
